/**
 * The Repositories section of the Code review settings: which repositories get automatic reviews,
 * each repository's rule and people lists (shared by the project), and the viewer's own default and
 * per-repository choices for their pull requests. Every write returns the repository with a fresh
 * `my_result`, so the "My pull requests" pane never computes the rule on the client.
 */
export const reviewHogRepositoriesLogic = kea<reviewHogRepositoriesLogicType>([
    path(['products', 'review_hog', 'frontend', 'repositories', 'reviewHogRepositoriesLogic']),

    connect(() => ({
        values: [integrationsLogic, ['integrations', 'githubIntegrations'], teamLogic, ['currentTeamId']],
        actions: [reviewHogSettingsLogic, ['updateSettings', 'updateSettingsSuccess']],
    })),

    actions({
        selectIntegration: (integrationId: number) => ({ integrationId }),
        setRepositoryToAdd: (fullName: string | null) => ({ fullName }),
        addRepository: true,
        addRepositorySuccess: (repository: ReviewRepositoryApi) => ({ repository }),
        addRepositoryFailure: true,
        removeRepository: (repository: ReviewRepositoryApi) => ({ repository }),
        removeRepositorySuccess: (repositoryId: string) => ({ repositoryId }),
        setFlashFor: (repository: ReviewRepositoryApi, flashFor: ReviewRepositoryFlashForEnumApi) => ({
            repository,
            flashFor,
        }),
        setExcludeBots: (repository: ReviewRepositoryApi, excludeBots: boolean) => ({ repository, excludeBots }),
        addPerson: (repository: ReviewRepositoryApi, userId: number, kind: ReviewRepositoryPersonKindEnumApi) => ({
            repository,
            userId,
            kind,
        }),
        removePerson: (repository: ReviewRepositoryApi, person: ReviewRepositoryPersonApi) => ({
            repository,
            person,
        }),
        setMyChoice: (repository: ReviewRepositoryApi, mode: ReviewUserRepositoryChoiceModeEnumApi) => ({
            repository,
            mode,
        }),
        clearMyChoice: (repository: ReviewRepositoryApi) => ({ repository }),
        setDefaultReviewMode: (mode: ReviewUserSettingsDefaultReviewModeEnumApi) => ({ mode }),
        // One write per repository at a time. The row's controls show the write as loading, and a
        // second write to the same repository waits for the user to retry after the first one lands.
        repositorySaveStarted: (repositoryId: string) => ({ repositoryId }),
        repositorySaved: (repository: ReviewRepositoryApi) => ({ repository }),
        repositorySaveFailed: (repositoryId: string) => ({ repositoryId }),
    }),

    loaders({
        repositories: [
            null as ReviewRepositoryApi[] | null,
            {
                loadRepositories: async () => await reviewHogRepositoriesList(currentProjectId()),
            },
        ],
    }),

    reducers({
        repositories: {
            addRepositorySuccess: (state, { repository }) => [...(state ?? []), repository],
            removeRepositorySuccess: (state, { repositoryId }) =>
                state?.filter((repository) => repository.id !== repositoryId) ?? state,
            repositorySaved: (state, { repository }) =>
                state?.map((existing) => (existing.id === repository.id ? repository : existing)) ?? state,
        },
        selectedIntegrationId: [
            null as number | null,
            {
                selectIntegration: (_, { integrationId }) => integrationId,
            },
        ],
        repositoryToAdd: [
            null as string | null,
            {
                setRepositoryToAdd: (_, { fullName }) => fullName,
                addRepositorySuccess: () => null,
            },
        ],
        addingRepository: [
            false,
            {
                addRepository: () => true,
                addRepositorySuccess: () => false,
                addRepositoryFailure: () => false,
            },
        ],
        repositoriesLoadFailed: [
            false,
            {
                loadRepositories: () => false,
                loadRepositoriesSuccess: () => false,
                loadRepositoriesFailure: () => true,
            },
        ],
        busyRepositoryIds: [
            [] as string[],
            {
                repositorySaveStarted: (state, { repositoryId }) => [...state, repositoryId],
                repositorySaved: (state, { repository }) => state.filter((id) => id !== repository.id),
                repositorySaveFailed: (state, { repositoryId }) => state.filter((id) => id !== repositoryId),
                removeRepositorySuccess: (state, { repositoryId }) => state.filter((id) => id !== repositoryId),
            },
        ],
    }),

    selectors({
        // Back to the Settings tab after GitHub authorizes, so the user lands on the picker again.
        connectGitHubUrl: [
            (s) => [s.currentTeamId],
            (currentTeamId: number | null): string =>
                `${getIntegrationsAuthorizeRetrieveUrl(String(currentTeamId))}?${new URLSearchParams({
                    kind: 'github',
                    next: combineUrl(urls.codeReview(), { tab: 'settings' }).url,
                })}`,
        ],
        githubIntegration: [
            (s) => [s.githubIntegrations, s.selectedIntegrationId],
            (githubIntegrations: IntegrationType[], selectedIntegrationId: number | null): IntegrationType | null =>
                githubIntegrations.find((integration) => integration.id === selectedIntegrationId) ??
                githubIntegrations[0] ??
                null,
        ],
    }),

    listeners(({ actions, values }) => {
        async function saveRepository(
            repositoryId: string,
            request: () => Promise<ReviewRepositoryApi>
        ): Promise<boolean> {
            if (values.busyRepositoryIds.includes(repositoryId)) {
                return false
            }
            actions.repositorySaveStarted(repositoryId)
            try {
                actions.repositorySaved(await request())
                return true
            } catch (error) {
                actions.repositorySaveFailed(repositoryId)
                lemonToast.error(errorDetail(error, 'Could not save the change. Try again.'))
                return false
            }
        }

        return {
            addRepository: async () => {
                const fullName = values.repositoryToAdd
                if (!fullName) {
                    actions.addRepositoryFailure()
                    return
                }
                try {
                    const repository = await reviewHogRepositoriesCreate(currentProjectId(), { full_name: fullName })
                    actions.addRepositorySuccess(repository)
                    // pinned: analytics event names in this file feed the Code review usage dashboards
                    posthog.capture('review hog repository added', { repository_id: repository.id })
                } catch (error) {
                    actions.addRepositoryFailure()
                    lemonToast.error(errorDetail(error, 'Could not add the repository. Try again.'))
                }
            },
            removeRepository: async ({ repository }) => {
                if (values.busyRepositoryIds.includes(repository.id)) {
                    return
                }
                actions.repositorySaveStarted(repository.id)
                try {
                    await reviewHogRepositoriesDestroy(currentProjectId(), repository.id)
                    actions.removeRepositorySuccess(repository.id)
                    posthog.capture('review hog repository removed', { repository_id: repository.id })
                } catch (error) {
                    actions.repositorySaveFailed(repository.id)
                    lemonToast.error(errorDetail(error, 'Could not remove the repository. Try again.'))
                }
            },
            setFlashFor: async ({ repository, flashFor }) => {
                const saved = await saveRepository(repository.id, () =>
                    reviewHogRepositoriesPartialUpdate(currentProjectId(), repository.id, { flash_for: flashFor })
                )
                if (saved) {
                    posthog.capture('review hog repository flash for changed', {
                        repository_id: repository.id,
                        flash_for: flashFor,
                    })
                }
            },
            setExcludeBots: async ({ repository, excludeBots }) => {
                const saved = await saveRepository(repository.id, () =>
                    reviewHogRepositoriesPartialUpdate(currentProjectId(), repository.id, {
                        exclude_bots: excludeBots,
                    })
                )
                if (saved) {
                    posthog.capture('review hog repository exclude bots changed', {
                        repository_id: repository.id,
                        exclude_bots: excludeBots,
                    })
                }
            },
            addPerson: async ({ repository, userId, kind }) => {
                const saved = await saveRepository(repository.id, () =>
                    reviewHogRepositoriesPeopleCreate(currentProjectId(), repository.id, { user_id: userId, kind })
                )
                if (saved) {
                    posthog.capture('review hog repository person added', { repository_id: repository.id, kind })
                }
            },
            removePerson: async ({ repository, person }) => {
                const saved = await saveRepository(repository.id, () =>
                    reviewHogRepositoriesPeopleDestroy(currentProjectId(), repository.id, person.id)
                )
                if (saved) {
                    posthog.capture('review hog repository person removed', {
                        repository_id: repository.id,
                        kind: person.kind,
                    })
                }
            },
            setMyChoice: async ({ repository, mode }) => {
                const saved = await saveRepository(repository.id, () =>
                    reviewHogRepositoriesMyChoiceUpdate(currentProjectId(), repository.id, { mode })
                )
                if (saved) {
                    posthog.capture('review hog repository choice set', { repository_id: repository.id, mode })
                }
            },
            clearMyChoice: async ({ repository }) => {
                const saved = await saveRepository(repository.id, () =>
                    reviewHogRepositoriesMyChoiceDestroy(currentProjectId(), repository.id)
                )
                if (saved) {
                    posthog.capture('review hog repository choice cleared', { repository_id: repository.id })
                }
            },
            setDefaultReviewMode: ({ mode }) => {
                actions.updateSettings({ default_review_mode: mode })
                posthog.capture('review hog default review mode changed', { mode })
            },
            updateSettingsSuccess: ({ payload }) => {
                // The default decides `my_result` in every repository without an own choice.
                if (payload && 'default_review_mode' in payload) {
                    actions.loadRepositories()
                }
            },
        }
    }),

    afterMount(({ actions }) => {
        actions.loadRepositories()
    }),
])
